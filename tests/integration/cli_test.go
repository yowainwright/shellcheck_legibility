var binaryPath string
var workspaceRoot string

func TestMain(m *testing.M) {
	root, err := filepath.Abs("../..")
	if err != nil {
		panic(err)
	}
	binaryPath = filepath.Join(root, "bin", "shellcheck-legibility")
	workspaceRoot = filepath.Join(root, ".build")
	os.Exit(m.Run())
}

func runBinary(t *testing.T, engine string, args ...string) (string, int) {
	t.Helper()
	t.Setenv("SHELLCHECK_LEGIBILITY_ENGINE", engine)
	command := exec.Command(binaryPath, args...)
	output, err := command.CombinedOutput()
	if err == nil {
		return string(output), 0
	}
	if command.ProcessState == nil {
		t.Fatalf("run make build first: %v", err)
	}
	return string(output), command.ProcessState.ExitCode()
}

func scanFixture(t *testing.T, engine string, fixture ruleFixture) []lint.Diagnostic {
	t.Helper()
	output, status := runBinary(t, engine, "check", fixture.path, "--select", fixture.code, "--no-cache", "--output-format", "json")
	if status != 1 {
		t.Fatalf("%s engine exited %d: %s", engine, status, output)
	}
	var findings []lint.Diagnostic
	if err := json.Unmarshal([]byte(output), &findings); err != nil {
		t.Fatal(err)
	}
	return findings
}

type ruleFixture struct{ code, path, source string }

func TestEveryRuleMatchesBash(t *testing.T) {
	enterTestWorkspace(t)
	fixtures := append(controlFixtures(), shellFixtures()...)
	for _, fixture := range fixtures {
		t.Run(fixture.code, func(t *testing.T) { compareRule(t, fixture) })
	}
}

