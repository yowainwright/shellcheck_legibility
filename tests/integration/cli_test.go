func compareRule(t *testing.T, fixture ruleFixture) {
	writeRuleFixture(t, fixture)
	expected := scanFixture(t, "bash", fixture)
	actual := scanFixture(t, "", fixture)
	if len(expected) == 0 {
		t.Fatal("fixture did not exercise the rule")
	}
	compareRuleJSON(t, expected, actual)
}

func writeRuleFixture(t *testing.T, fixture ruleFixture) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(fixture.path), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(fixture.path, []byte(fixture.source), 0600); err != nil {
		t.Fatal(err)
	}
}

func compareRuleJSON(t *testing.T, expected, actual []lint.Diagnostic) {
	t.Helper()
	expectJSON, _ := json.Marshal(expected)
	actualJSON, _ := json.Marshal(actual)
	if string(expectJSON) != string(actualJSON) {
		t.Fatalf("expected %s\nactual   %s", expectJSON, actualJSON)
	}
}

func TestIncompleteShellKeepsFeedbackWithoutExecutingSource(t *testing.T) {
	enterTestWorkspace(t)
	source := "touch executed\nrun() { create_user true;\n"
	if err := os.WriteFile("incomplete.sh", []byte(source), 0600); err != nil {
		t.Fatal(err)
	}
	findings := scanFixture(t, "", ruleFixture{"LEG035", "incomplete.sh", source})
	if len(findings) != 1 || findings[0].Code != "LEG035" {
		t.Fatalf("findings: %+v", findings)
	}
	if _, err := os.Stat("executed"); !os.IsNotExist(err) {
		t.Fatal("scanned source was executed")
	}
}

func TestNativeEngineDoesNotRequireBash(t *testing.T) {
	enterTestWorkspace(t)
	writeRuleFixture(t, ruleFixture{path: "incomplete.sh", source: "run() { create_user true;\n"})
	t.Setenv("PATH", "")
	output, status := runBinary(t, "", "check", "incomplete.sh", "--select", "LEG035", "--no-cache")
	if status != 1 || !strings.Contains(output, "LEG035") {
		t.Fatalf("status %d: %s", status, output)
	}
	writeRuleFixture(t, ruleFixture{path: "unrecoverable.sh", source: "create_user true\nunexpected)\n"})
	writeRuleFixture(t, ruleFixture{path: "remaining.sh", source: "create_user true\n"})
	output, status = runBinary(t, "", "check", "unrecoverable.sh", "remaining.sh", "--select", "LEG035", "--no-cache")
	if status != 2 || strings.Count(output, "LEG035") != 2 || !strings.Contains(output, "unrecoverable.sh") || !strings.Contains(output, "remaining.sh") || strings.Contains(output, "Bash is required") {
		t.Fatalf("status %d: %s", status, output)
	}
}

func TestNativeScanDoesNotRequireBash(t *testing.T) {
	enterTestWorkspace(t)
	t.Setenv("PATH", "")
	fixture := ruleFixture{"LEG035", "example.sh", "create_user true\n"}
	writeRuleFixture(t, fixture)
	if findings := scanFixture(t, "", fixture); len(findings) != 1 {
		t.Fatalf("findings: %+v", findings)
	}
}

func TestMalformedSourceKeepsRuleFeedback(t *testing.T) {
	enterTestWorkspace(t)
	fixtures := []ruleFixture{
		{"LEG042", "example.sh", "value=\"$(\n  case \"$target\" in\n    x) # Generated by codex.\n"},
		{"LEG040", "example.sh", "deploy()\n{\nlocal target=\"$1\"\n"},
	}
	for _, fixture := range fixtures {
		t.Run(fixture.code, func(t *testing.T) { compareRule(t, fixture) })
	}
}

func enterTestWorkspace(t *testing.T) {
	t.Helper()
	if err := os.MkdirAll(workspaceRoot, 0755); err != nil {
		t.Fatal(err)
	}
	dir, err := os.MkdirTemp(workspaceRoot, "integration-")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { os.RemoveAll(dir) })
	t.Chdir(dir)
}
